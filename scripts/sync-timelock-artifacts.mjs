// Copies the compiled timed-lock contracts into the app and pins the factory's address.
// Run after changing contracts/: (cd contracts && forge build) && npm run sync:timelock
//
// The factory is deployed through the CREATE2 deployer with a fixed salt and fixed
// constructor args, so its address is known before it exists - and whoever sends the
// deploy transaction, the result is the same contract owned by the AeroLock treasury.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { encodeAbiParameters, getContractAddress, keccak256, toHex } from 'viem';

const read = (name) => JSON.parse(readFileSync(`contracts/out/${name}.sol/${name}.json`, 'utf8'));
const factory = read('AeroLockFactory');
const vault = read('AeroVestingVault');

const TREASURY = '0xc0dca68EFdCC63aD109B301585b4b8E38cAe344e';
const args = {
  owner: TREASURY,
  treasury: TREASURY,
  feeUsd: 150n * 10n ** 8n, // $150
  feePerExtraLockUsd: 25n * 10n ** 8n, // +$25 per extra wallet in a team batch
  aerodromeFactory: '0x420DD381b31aEf6683db6B902084cB0FFECe40Da',
  priceFeed: '0x71041dddad3595F9CEd3DcCFBe3D1F4b0a16Bb70', // Chainlink ETH/USD on Base
  sequencerFeed: '0xBCF85224fc0756B9Fa45aA7892530B47e10b6433', // Chainlink Base sequencer uptime
};
// v2 added createLocks (team vesting); v1 lives on at 0x07E05724Be95Ea989F66471F822fB489aCFb83ea
const SALT = keccak256(toHex('aerolock.timelock.v2'));
const CREATE2_DEPLOYER = '0x4e59b44847b379578588920cA78FbF26c0B4956C';

const encodedArgs = encodeAbiParameters(
  [
    { type: 'address' },
    { type: 'address' },
    { type: 'uint256' },
    { type: 'uint256' },
    { type: 'address' },
    { type: 'address' },
    { type: 'address' },
  ],
  [args.owner, args.treasury, args.feeUsd, args.feePerExtraLockUsd, args.aerodromeFactory, args.priceFeed, args.sequencerFeed],
);
const initCode = factory.bytecode.object + encodedArgs.slice(2);
const address = getContractAddress({ opcode: 'CREATE2', from: CREATE2_DEPLOYER, salt: SALT, bytecode: initCode });

writeFileSync(
  'src/lib/web3/timelock/artifacts.ts',
  `// Generated by scripts/sync-timelock-artifacts.mjs from contracts/out - do not edit.\n` +
    `export const TIMELOCK_FACTORY_ADDRESS = '${address}' as const;\n` +
    `export const TIMELOCK_CREATE2_DEPLOYER = '${CREATE2_DEPLOYER}' as const;\n` +
    `export const TIMELOCK_FACTORY_SALT = '${SALT}' as const;\n` +
    `/** creation bytecode + constructor args */\n` +
    `export const TIMELOCK_FACTORY_INITCODE = '${initCode}' as const;\n` +
    `export const TIMELOCK_FACTORY_CONSTRUCTOR_ARGS = '${encodedArgs}' as const;\n` +
    `export const TIMELOCK_FACTORY_ABI = ${JSON.stringify(factory.abi)} as const;\n` +
    `export const TIMELOCK_VAULT_ABI = ${JSON.stringify(vault.abi)} as const;\n`,
);
console.log(`wrote src/lib/web3/timelock/artifacts.ts - factory will live at ${address}`);

// Source bundle for Basescan verification (edge functions can't read contracts/).
// The factory's standard JSON input includes every file the vault needs too.
const standardInput = execSync(
  `forge verify-contract ${address} src/AeroLockFactory.sol:AeroLockFactory --show-standard-json-input`,
  { cwd: 'contracts', encoding: 'utf8' },
);
const compilerVersion = `v${JSON.parse(factory.rawMetadata).compiler.version}`;
writeFileSync(
  'supabase/functions/_shared/timelockSources.ts',
  `// Generated by scripts/sync-timelock-artifacts.mjs from contracts/ - do not edit.\n` +
    `export const TIMELOCK_FACTORY_ADDRESS = '${address}';\n` +
    `export const TIMELOCK_FACTORY_CONSTRUCTOR_ARGS = '${encodedArgs.slice(2)}';\n` +
    `export const TIMELOCK_COMPILER_VERSION = '${compilerVersion}';\n` +
    `export const TIMELOCK_STANDARD_INPUT = ${JSON.stringify(JSON.stringify(JSON.parse(standardInput)))};\n`,
);
console.log(`wrote supabase/functions/_shared/timelockSources.ts (${compilerVersion})`);
