// Copies the compiled 30-day-notice LPLocker (v2) into the app and the edge functions.
// Run after changing contracts/locker/: (cd contracts && FOUNDRY_PROFILE=locker forge build) && npm run sync:locker
//
// v2 claims fees from both legacy Aerodrome pools and Aero pools (Oct 2026+). Lockers already
// deployed run v1 and stay valid; the edge functions recognise both by code fingerprint.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { keccak256 } from 'viem';

const art = JSON.parse(readFileSync('contracts/out-locker/LPLocker.sol/LPLocker.json', 'utf8'));
const bytecode = art.bytecode.object;
// immutables (the token address) are zero in the compiler's runtime code, exactly as
// inspectLocker masks them in a deployed locker
const fingerprint = keccak256(art.deployedBytecode.object);
const compilerVersion = `v${JSON.parse(art.rawMetadata).compiler.version}`;

writeFileSync(
  'src/lib/web3/LPLockerBytecode.ts',
  `// Generated by scripts/sync-locker-artifacts.mjs from contracts/locker - do not edit.\n` +
    `// LPLocker v2: claims fees from legacy Aerodrome pools and Aero pools.\n` +
    `export const LP_LOCKER_VERSION = 2;\n\n` +
    `export const LP_LOCKER_BYTECODE = '${bytecode}' as const;\n\n` +
    `// Constructor ABI for deployment\n` +
    `export const LP_LOCKER_CONSTRUCTOR_ABI = [\n` +
    `  {\n` +
    `    inputs: [\n` +
    `      { name: 'tokenContract_', type: 'address' },\n` +
    `      { name: 'owner_', type: 'address' },\n` +
    `      { name: 'feeReceiver_', type: 'address' }\n` +
    `    ],\n` +
    `    stateMutability: 'nonpayable',\n` +
    `    type: 'constructor'\n` +
    `  }\n` +
    `] as const;\n`,
);

// Basescan verification bundle for v2 lockers (exact settings and file paths)
const standardInput = execSync(
  'forge verify-contract 0x0000000000000000000000000000000000000001 locker/LPLocker.sol:LPLocker --show-standard-json-input',
  { cwd: 'contracts', encoding: 'utf8', env: { ...process.env, FOUNDRY_PROFILE: 'locker' } },
);
writeFileSync(
  'supabase/functions/_shared/lockerV2.ts',
  `// Generated by scripts/sync-locker-artifacts.mjs from contracts/locker - do not edit.\n` +
    `export const LOCKER_V2_FINGERPRINT = '${fingerprint}';\n` +
    `export const LOCKER_V2_COMPILER_VERSION = '${compilerVersion}';\n` +
    `export const LOCKER_V2_CONTRACT_NAME = 'locker/LPLocker.sol:LPLocker';\n` +
    `export const LOCKER_V2_STANDARD_INPUT = ${JSON.stringify(JSON.stringify(JSON.parse(standardInput)))};\n`,
);
console.log(`LPLocker v2 synced (${compilerVersion}), fingerprint ${fingerprint}`);
